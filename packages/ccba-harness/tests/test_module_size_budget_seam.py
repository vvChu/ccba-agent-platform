"""Tests for the Tier-0 stdlib _module_size_budget seam and Hub/Spoke wiring."""

from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

pytestmark = [pytest.mark.fast, pytest.mark.unit]

REPO_ROOT = Path(__file__).resolve().parents[3]
SEAM_PATH = REPO_ROOT / "packages/ccba-harness/src/ccba_harness/_module_size_budget.py"


def _load_isolated_seam() -> Any:
    spec = importlib.util.spec_from_file_location("_isolated_module_size_budget", SEAM_PATH)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_seam_file_budget_and_pure_stdlib_import(monkeypatch: pytest.MonkeyPatch) -> None:
    """Seam must stay <= 120 LOC and load cleanly without pydantic or ccba_harness."""
    line_count = len(SEAM_PATH.read_text(encoding="utf-8-sig").splitlines())
    assert line_count <= 120, f"_module_size_budget.py grew to {line_count} > 120 LOC"

    monkeypatch.setitem(sys.modules, "pydantic", None)
    monkeypatch.setitem(sys.modules, "ccba_harness", None)
    mod = _load_isolated_seam()
    assert hasattr(mod, "iter_production_files")
    assert hasattr(mod, "evaluate_module_budgets")
    assert hasattr(mod, "compute_ratchet_baseline")


def test_codegen_exemption_vs_handwritten_js_and_pruning(tmp_path: Path) -> None:
    """Auto-generated Python models are exempted while handwritten .js monoliths are caught."""
    mod = _load_isolated_seam()
    models_py = tmp_path / "tools" / "validator" / "models.py"
    gen_py = tmp_path / "tools" / "validator" / "schema_generated.py"
    dict_js = tmp_path / "tools" / "templates" / "html_cockpit" / "dictionary.js"
    cockpit_js = tmp_path / "tools" / "templates" / "html_cockpit" / "cockpit.js"
    ignored_test = tmp_path / "tools" / "tests" / "test_big.py"
    ignored_guard = tmp_path / "scripts" / "_guardrails" / "huge.py"

    for p in (models_py, gen_py, dict_js, cockpit_js, ignored_test, ignored_guard):
        p.parent.mkdir(parents=True, exist_ok=True)

    models_py.write_text(
        '"""Generated Pydantic v2 models.\nDO NOT EDIT DIRECTLY. Generated by codegen.\n"""\n'
        + "\n".join(["x = 1"] * 1125)
        + "\n",
        encoding="utf-8",
    )
    gen_py.write_text("\n".join(["y = 2"] * 850) + "\n", encoding="utf-8")
    dict_js.write_text(
        "/**\n * IDOP Dictionary Controller\n */\n" + "\n".join(["var a = 1;"] * 850) + "\n",
        encoding="utf-8",
    )
    cockpit_js.write_text(
        "/**\n * IDOP Cockpit Controller\n */\n" + "\n".join(["var b = 1;"] * 850) + "\n",
        encoding="utf-8",
    )
    ignored_test.write_text("\n".join(["z = 3"] * 900) + "\n", encoding="utf-8")
    ignored_guard.write_text("\n".join(["g = 4"] * 900) + "\n", encoding="utf-8")

    files = mod.iter_production_files(tmp_path)
    rels = [f.relative_to(tmp_path).as_posix() for f in files]
    assert "tools/tests/test_big.py" not in rels
    assert "scripts/_guardrails/huge.py" not in rels
    assert rels == sorted(rels)

    violations = mod.evaluate_module_budgets(tmp_path, files, baseline={}, hard_lines=800)
    assert len(violations) == 2
    assert any("dictionary.js" in v and "hard cap exceeded" in v for v in violations)
    assert any("cockpit.js" in v and "hard cap exceeded" in v for v in violations)


def test_symlinks_bom_and_unreadable_fail_closed(tmp_path: Path) -> None:
    """Symlinks are skipped, UTF-8 BOM is handled, and invalid bytes fail closed."""
    mod = _load_isolated_seam()
    tools_dir = tmp_path / "tools"
    tools_dir.mkdir(parents=True)
    bom_py = tools_dir / "bom_module.py"
    bom_py.write_bytes(b"\xef\xbb\xbf" + b"\n".join([b"x = 1"] * 805) + b"\n")

    bad_utf8 = tools_dir / "corrupt.py"
    bad_utf8.write_bytes(b"\xff\xfe\x80\x81\n")

    outside = tmp_path / "outside.py"
    outside.write_text("\n".join(["k = 1"] * 900) + "\n", encoding="utf-8")
    sym_file = tools_dir / "link.py"
    sym_dir_target = tmp_path / "outside_dir"
    sym_dir_target.mkdir()
    (sym_dir_target / "secret.py").write_text("\n".join(["s = 1"] * 900) + "\n", encoding="utf-8")
    sym_dir = tools_dir / "linked_sub"
    try:
        sym_file.symlink_to(outside)
        sym_dir.symlink_to(sym_dir_target, target_is_directory=True)
    except OSError:
        pytest.skip("Symlink creation requires elevated privileges on this OS")

    files = mod.iter_production_files(tmp_path)
    rels = [f.relative_to(tmp_path).as_posix() for f in files]
    assert "tools/link.py" not in rels
    assert "tools/linked_sub/secret.py" not in rels
    assert rels == ["tools/bom_module.py", "tools/corrupt.py"]

    violations = mod.evaluate_module_budgets(tmp_path, files, baseline={}, hard_lines=800)
    assert any(
        "tools/bom_module.py: hard cap exceeded (805 lines > 800 LOC limit)" in v
        for v in violations
    )
    assert any("tools/corrupt.py: cannot read file:" in v for v in violations)


def test_compute_ratchet_baseline_monotonic(tmp_path: Path) -> None:
    """Ratchet lowers ceilings when shrunk, drops <=800 files, and never raises ceilings."""
    mod = _load_isolated_seam()
    tools_dir = tmp_path / "tools"
    tools_dir.mkdir(parents=True)
    shrunk = tools_dir / "shrunk.py"
    under_cap = tools_dir / "under_cap.py"
    new_over = tools_dir / "new_over.py"
    grown = tools_dir / "grown.py"

    shrunk.write_text("\n".join(["a = 1"] * 840) + "\n", encoding="utf-8")
    under_cap.write_text("\n".join(["b = 1"] * 790) + "\n", encoding="utf-8")
    new_over.write_text("\n".join(["c = 1"] * 815) + "\n", encoding="utf-8")
    grown.write_text("\n".join(["d = 1"] * 860) + "\n", encoding="utf-8")

    existing = {
        "tools/shrunk.py": 950,
        "tools/under_cap.py": 830,
        "tools/grown.py": 850,
    }
    files = mod.iter_production_files(tmp_path)
    updated = mod.compute_ratchet_baseline(tmp_path, files, existing=existing, hard_lines=800)
    assert updated == {
        "tools/grown.py": 850,
        "tools/new_over.py": 815,
        "tools/shrunk.py": 840,
    }


def test_spoke_cleanliness_preserves_strict_when_baseline_missing(tmp_path: Path) -> None:
    """Missing Spoke baseline preserves strict=True exit_code=0 unless explicitly enforced."""
    from scripts.spoke.check_spoke_cleanliness import scan_spoke_cleanliness

    scripts_dir = tmp_path / "scripts"
    scripts_dir.mkdir()
    big_tool = tmp_path / "tools" / "big.py"
    big_tool.parent.mkdir(parents=True)
    big_tool.write_text("\n".join(["x = 1"] * 850) + "\n", encoding="utf-8")

    rc_strict, msgs_strict = scan_spoke_cleanliness(tmp_path, max_scripts=15, strict=True)
    assert rc_strict == 0
    assert any("bỏ qua kiểm tra" in m for m in msgs_strict)

    rc_enforced, msgs_enforced = scan_spoke_cleanliness(
        tmp_path, max_scripts=15, strict=False, enforce_module_budget=True
    )
    assert rc_enforced == 1
    assert any("tools/big.py" in m for m in msgs_enforced)

    base_file = scripts_dir / "_guardrails" / "module_budget_baseline.json"
    base_file.parent.mkdir(parents=True)
    base_file.write_text(json.dumps({"tools/big.py": 840}), encoding="utf-8")
    rc_base, msgs_base = scan_spoke_cleanliness(tmp_path, max_scripts=15, strict=False)
    assert rc_base == 1
    assert any("ratchet violation" in m for m in msgs_base)


def _run_isolated_spoke_checker(spoke_dir: Path, checker_path: Path) -> tuple[int, list[str]]:
    runner = "\n".join(
        [
            "import importlib.util, json, sys",
            "from pathlib import Path",
            "sys.modules['ccba_harness'] = None",
            f"spec = importlib.util.spec_from_file_location('iso_spoke', Path({str(checker_path)!r}))",
            "mod = importlib.util.module_from_spec(spec)",
            "spec.loader.exec_module(mod)",
            f"code, msgs = mod.scan_spoke_cleanliness(Path({str(spoke_dir)!r}), strict=True)",
            "print(json.dumps({'code': code, 'msgs': msgs}))",
        ]
    )
    proc = subprocess.run(
        [sys.executable, "-c", runner], capture_output=True, text=True, check=True
    )
    payload = json.loads(proc.stdout)
    return int(payload["code"]), list(payload["msgs"])


def test_spoke_tier0_isolation_with_and_without_budget_seam(tmp_path: Path) -> None:
    """Isolated Tier-0 Spoke runs cleanly without baseline/seam, and enforces once synced."""
    guardrails = tmp_path / "scripts" / "_guardrails"
    guardrails.mkdir(parents=True)
    checker = guardrails / "check_spoke_cleanliness.py"
    shutil.copy2(REPO_ROOT / "scripts/spoke/check_spoke_cleanliness.py", checker)
    shutil.copy2(
        REPO_ROOT / "packages/ccba-harness/src/ccba_harness/_parameter_cleanliness.py",
        guardrails / "_parameter_cleanliness.py",
    )
    big_file = tmp_path / "tools" / "big.py"
    big_file.parent.mkdir(parents=True)
    big_file.write_text("\n".join(["x = 1"] * 850) + "\n", encoding="utf-8")

    code_no_seam, _ = _run_isolated_spoke_checker(tmp_path, checker)
    assert code_no_seam == 0

    (guardrails / "module_budget_baseline.json").write_text("{}", encoding="utf-8")
    code_missing_seam, msgs_missing_seam = _run_isolated_spoke_checker(tmp_path, checker)
    assert code_missing_seam == 1
    assert any("Thiếu _module_size_budget.py" in m for m in msgs_missing_seam)

    shutil.copy2(SEAM_PATH, guardrails / "_module_size_budget.py")
    code_with_seam, msgs_with_seam = _run_isolated_spoke_checker(tmp_path, checker)
    assert code_with_seam == 1
    assert any("tools/big.py: hard cap exceeded" in m for m in msgs_with_seam)
