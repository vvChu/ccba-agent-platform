"""Pure-stdlib enumerator and ratchet evaluator for module size budgets.

Shared Tier-0 seam used by ``ccba_harness.peer_gate`` and
``scripts/_guardrails/check_spoke_cleanliness.py``.
"""

from __future__ import annotations

import os
from collections.abc import Sequence
from pathlib import Path

DEFAULT_PRODUCTION_ROOTS: tuple[str, ...] = tuple(
    "packages/*/src tools services backend formulas scripts".split()
)
TRACKED_EXTENSIONS: frozenset[str] = frozenset(".py .js .ts .tsx".split())
PRUNED_DIRS: frozenset[str] = frozenset(
    "node_modules .venv venv tests _guardrails __pycache__ .md .git".split()
)
CODEGEN_MARKERS: tuple[str, ...] = ("auto-generated", "do not edit", "generated by")


def is_codegen_exempt(path: Path, lines: Sequence[str]) -> bool:
    """Return True when a module is auto-generated and exempt from line caps."""
    if path.suffix == ".py" and "_generated" in path.stem.lower():
        return True
    head = "\n".join(lines[:10]).lower()
    return any(marker in head for marker in CODEGEN_MARKERS)


def iter_production_files(ws: Path, roots: Sequence[str] = DEFAULT_PRODUCTION_ROOTS) -> list[Path]:
    """Deterministically enumerate tracked production files across configured roots."""
    ws_r = ws.resolve()
    seen: dict[str, Path] = {}
    for root in roots:
        bases = (
            sorted(ws_r.glob(root), key=lambda p: p.as_posix()) if "*" in root else [ws_r / root]
        )
        for base in bases:
            if not base.is_dir() or base.is_symlink():
                continue
            for dirpath, dirnames, filenames in os.walk(base, topdown=True, followlinks=False):
                cur = Path(dirpath)
                dirnames[:] = sorted(
                    d for d in dirnames if d not in PRUNED_DIRS and not (cur / d).is_symlink()
                )
                for fn in sorted(filenames):
                    cand = cur / fn
                    if not cand.is_symlink() and cand.suffix in TRACKED_EXTENSIONS:
                        seen.setdefault(cand.resolve().relative_to(ws_r).as_posix(), cand)
    return [seen[key] for key in sorted(seen)]


def _safe_read_lines(path: Path) -> tuple[list[str] | None, str | None]:
    """Decode a text file using UTF-8-SIG and return split lines or an error string."""
    try:
        return path.read_text(encoding="utf-8-sig").splitlines(), None
    except (OSError, UnicodeDecodeError) as exc:
        return None, str(exc)


def evaluate_module_budgets(
    ws: Path, files: Sequence[Path], baseline: dict[str, int], hard_lines: int = 800
) -> list[str]:
    """Evaluate module line counts against ratchet baselines and hard caps."""
    ws_r = ws.resolve()
    violations: list[str] = []
    for mod_file in files:
        resolved = mod_file.resolve() if mod_file.is_absolute() else (ws_r / mod_file).resolve()
        rel = resolved.relative_to(ws_r).as_posix()
        lines, err = _safe_read_lines(mod_file)
        if lines is None:
            violations.append(f"{rel}: cannot read file: {err}")
            continue
        if is_codegen_exempt(mod_file, lines):
            continue
        loc = len(lines)
        if rel in baseline:
            if loc > baseline[rel]:
                violations.append(
                    f"{rel}: ratchet violation ({loc} lines > committed baseline {baseline[rel]})"
                )
        elif loc > hard_lines:
            violations.append(f"{rel}: hard cap exceeded ({loc} lines > {hard_lines} LOC limit)")
    return violations


def compute_ratchet_baseline(
    ws: Path, files: Sequence[Path], existing: dict[str, int] | None = None, hard_lines: int = 800
) -> dict[str, int]:
    """Compute a monotonic ratchet baseline mapping for oversized handwritten files."""
    ws_r = ws.resolve()
    updated: dict[str, int] = {}
    for mod_file in files:
        lines, err = _safe_read_lines(mod_file)
        if lines is None:
            raise OSError(f"Cannot read {mod_file}: {err}")
        if is_codegen_exempt(mod_file, lines):
            continue
        loc = len(lines)
        if loc <= hard_lines:
            continue
        rel = mod_file.resolve().relative_to(ws_r).as_posix()
        prev = existing.get(rel) if existing is not None else None
        updated[rel] = min(prev, loc) if prev is not None else loc
    return dict(sorted(updated.items()))
